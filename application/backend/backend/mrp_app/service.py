    def update_settings(self, body):
        try:
            return self.settings.update(body)
        except ValueError as exc:
            raise AppError(str(exc)) from exc

    def import_model_zip(self, project_id, label, archive_path):
        """Install a checkpoint zip produced elsewhere (notebook, GPU server)."""
        project = self.project(project_id)
        label = (label or "").strip()
        if len(label) > 80 or any(ord(c) < 32 for c in label):
            raise AppError("Label must be at most 80 printable characters.")
        try:
            run_id, path = model_files.import_checkpoint_zip(archive_path, self.runs_dir, label)
        except model_files.ModelImportError as exc:
            raise AppError(str(exc)) from exc
        self.store.execute(
            "INSERT INTO models (id,project_id,source,label,path,state,created,payload) VALUES (?,?,?,?,?,?,?,?)",
            (run_id, project["id"], "checkpoint_import", label, path, "complete", time.time(), "{}"),
        )
        return self.store.rows("SELECT * FROM models WHERE id=?", (run_id,))[0]

    def import_hub_model(self, body):
        request_id = self.request_id(body)
        with self.lock:
            previous = self.store.rows("SELECT * FROM models WHERE id=?", (request_id,))
            if previous:
                return previous[0]
            project = self.project(body.get("project_id"))
            if not self.agent_url:
                raise AppError("Model import needs the deployment agent.", 503)
            repo_id = body.get("repo_id")
            if not isinstance(repo_id, str) or not re.fullmatch(
                r"[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", repo_id
            ):
                raise AppError("Repository must use namespace/name syntax (paste the URL's last two parts).")
            revision = body.get("revision") or None
            subfolder = body.get("subfolder") or ""
            label = (body.get("label") or "").strip()
            if len(label) > 80:
                raise AppError("Label must be at most 80 printable characters.")
            token = self.settings.token() if body.get("use_saved_token") else None
            if body.get("use_saved_token") and not token:
                raise AppError(
                    "No Hugging Face token is saved. Add one in Settings, or import a public model."
                )
            if self.store.rows("SELECT id FROM models WHERE state='importing'"):
                raise AppError("A model import is already running.", 409)
            payload = {"repo_id": repo_id, "revision": revision, "subfolder": subfolder}
            self.store.execute(
                "INSERT INTO models (id,project_id,source,label,path,state,created,payload,detail) VALUES (?,?,?,?,?,?,?,?,?)",
                (
                    request_id,
                    project["id"],
                    "huggingface",
                    label or repo_id,
                    model_files.canonical_model_path(request_id),
                    "importing",
                    time.time(),
                    json.dumps(payload),
                    "Downloading from the Hugging Face Hub…",
                ),
            )
            self.jobs.start(
                JobKind.IMPORT,
                request_id,
                partial(self.jobs.import_hub, self.agent_url, request_id, payload, label, token),
            )
            return self.store.rows("SELECT * FROM models WHERE id=?", (request_id,))[0]

    def dataset_folder(self, export_id, project_id=None):
        """Folder of a completed export, for ZIP download. Never follows symlinks."""
        if not canonical_uuid(export_id):
            raise AppError("Invalid export.", 404)
        rows = self.store.rows("SELECT * FROM jobs WHERE id=? AND state='complete'", (export_id,))
        if not rows or (project_id and rows[0].get("project_id") != project_id):
            raise AppError("Completed export not found.", 404)
        folder = self.exports_dir / export_id / "dataset"
        if folder.is_symlink() or not (folder / "meta/info.json").is_file():
            raise AppError("Export dataset is missing.", 404)
        return folder.resolve(), rows[0]

    def notebook_for(self, project_id, params):
        project = self.project(project_id)
        task = TASKS[project["cell_spec"]["task_id"]]["label"]
        settings = {}
        for key, default in (("steps", 1000), ("batch_size", 8), ("chunk_size", 100)):
            try:
                value = int(params.get(key, [default])[0])
            except ValueError as exc:
                raise AppError(f"{key} must be an integer.") from exc
            if not 1 <= value <= 200000:
                raise AppError(f"{key} is out of range.")
            settings[key] = value
        source = params.get("source", ["zip"])[0]
        repo = params.get("repo_id", [""])[0]
        if source not in ("zip", "hub"):
            raise AppError("source must be zip or hub.")
        if source == "hub" and not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", repo
        ):
            raise AppError("Enter the dataset repository as namespace/name.")
        return notebook.dumps(project["name"], task, settings, source, repo or None)

    def close(self):
        self.recording.close()
        try:
            self.jobs.close()
        finally:
            self.runtime.close()
