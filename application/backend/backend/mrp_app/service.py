    def config_export(self):
        """Write a new bundle of all calibrations, robot profiles and cell configs to the user data volume."""
        calibrations, note = self._local_calibrations()
        with self.lock:
            projects = [
                self._with_cell(row) for row in self.store.rows("SELECT * FROM projects ORDER BY created")
            ]
        for project in projects:
            if not project["layout_saved"]:
                project["cell_layout"] = None
        data = configbundle.build_bundle(calibrations, projects, self.robots(), __version__)
        folder = self.user_data_dir / "backups"
        folder.mkdir(parents=True, exist_ok=True)
        stamp = time.strftime("mrp-config-%Y%m%d-%H%M%S", time.gmtime())
        name, number = f"{stamp}.tar.gz", 0
        while (folder / name).exists():
            number += 1
            name = f"{stamp}-{number}.tar.gz"
        temporary = folder / (name + ".tmp")
        temporary.write_bytes(data)
        temporary.replace(folder / name)
        return {
            "name": name,
            "bytes": len(data),
            "counts": {
                "calibrations": len(calibrations),
                "projects": len(projects),
                "robots": len(self.robots()),
            },
            "warnings": [note] if note else [],
        }

    def config_backup_path(self, name):
        if not isinstance(name, str) or not configbundle.BACKUP_NAME.fullmatch(name):
            raise AppError("Invalid backup name.")
        path = self.user_data_dir / "backups" / name
        if path.is_symlink() or not path.is_file():
            raise AppError("Backup not found.", 404)
