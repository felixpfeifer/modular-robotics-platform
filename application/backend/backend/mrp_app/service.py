    def workflow(self, ident):
        """Per-project stage summary that drives the guided pages."""
        project = self.project(ident)
        episodes, _ = self.artifacts.list()
        mine = {row["id"] for row in self.store.rows("SELECT id FROM sessions WHERE project_id=?", (ident,))}
        accepted = [e["id"] for e in episodes if e["id"] in mine and e["status"] == "accepted"]
        exports = self.store.rows("SELECT * FROM jobs WHERE project_id=? ORDER BY created DESC", (ident,))
        deployments = self.store.rows(
            "SELECT * FROM deployments WHERE project_id=? ORDER BY created DESC", (ident,)
        )
        done_exports = [j for j in exports if j["state"] == "complete"]
        done_trainings = self.store.rows(
            "SELECT * FROM models WHERE project_id=? AND state='complete'", (ident,)
        )
        running_policy = [d for d in deployments if d["state"] in ("starting", "running")]
        preset = PRESETS[project["preset"]]
        stages = [
            {"id": "setup", "label": "Cell", "state": "done", "summary": preset["label"]},
            {
                "id": "record",
                "label": "Record",
                "state": "done" if accepted else "todo",
                "summary": f"{len(accepted)} accepted episode(s)",
            },
            {
                "id": "dataset",
                "label": "Dataset",
                "state": "done" if done_exports else ("todo" if accepted else "blocked"),
                "summary": f"{len(done_exports)} export(s)",
                "blocked_reason": "Record and accept an episode first.",
            },
            {
                "id": "train",
                "label": "Model",
                "state": "done" if done_trainings else ("todo" if done_exports else "blocked"),
                "summary": f"{len(done_trainings)} model(s)",
                "blocked_reason": "Export a dataset first.",
            },
            {
                "id": "deploy",
                "label": "Deploy",
                "state": "active" if running_policy else "todo",
                "summary": "policy running" if running_policy else "not running",
            },
        ]
        return {
            "project": project,
            "stages": stages,
            "accepted_episode_ids": accepted,
            "task": TASKS[project["cell_spec"]["task_id"]],
        }

