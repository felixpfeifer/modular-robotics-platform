    RUN_MODEL = re.compile(
        r"(?:/data/runs/)?([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})"
        r"/output/checkpoints/(last|[0-9]{1,10})/pretrained_model"
    )

    def model_path(self, text):
        """Normalise a user-entered model path to '<run-uuid>/output/checkpoints/<n>/pretrained_model'."""
        match = self.RUN_MODEL.fullmatch(text.strip()) if isinstance(text, str) else None
        if not match:
            raise AppError(
                "Model path must look like <run-id>/output/checkpoints/last/pretrained_model "
                "inside the training runs volume."
            )
        return f"{match[1]}/output/checkpoints/{match[2]}/pretrained_model"

    def _training_device(self, body, smoke):
        """Pick cuda or cpu. Training on the CPU without a GPU is slow, so it needs an explicit confirmation."""
        requested = body.get("device", "auto")
        if requested not in ("auto", "cuda", "cpu"):
            raise AppError("device must be auto, cuda or cpu.")
        hardware = self.hardware()
        has_gpu = hardware.get("gpu") is True
        if requested == "cuda" and not has_gpu:
            raise AppError(
                "No usable NVIDIA GPU was detected"
                + (f": {hardware['detail']}" if hardware.get("detail") else ".")
                + " Choose CPU training or fix the GPU setup.",
                409,
            )
        device = "cuda" if requested == "cuda" or (requested == "auto" and has_gpu) else "cpu"
        if device == "cpu" and not has_gpu and not smoke and body.get("confirm_cpu") is not True:
            raise AppError(
                "No usable NVIDIA GPU was detected"
                + (f" ({hardware['detail']})" if hardware.get("detail") else "")
                + ". Training on the CPU can take many hours; confirm to continue.",
                409,
            )
        return device

    def train(self, body):
        request_id = self.request_id(body)
        runtime = body.get("runtime") or "lerobot_act"
        if body.get("target") not in (None, "local") or runtime != "lerobot_act":
            self._check_runtime_choice(runtime, body.get("target"))
            raise AppError(
                "Only local ACT training is wired in. For other containers or remote targets use "
                "'Get launch command' and register the pushed model from the Hub.",
                501,
            )
        with self.lock:
            previous = self.store.rows("SELECT * FROM trainings WHERE request_id=?", (request_id,))
            if previous:
                return previous[0]
            project = self.project(body.get("project_id"))
            if not self.agent_url:
                raise AppError("Training needs the deployment agent.", 503)
            exports = self.store.rows(
                "SELECT * FROM jobs WHERE id=? AND state='complete' AND project_id=?",
                (body.get("export_id"), project["id"]),
            )
            if not exports:
                raise AppError("Choose a completed dataset export of this project.", 409)
            settings = body.get("settings") or {}
            allowed = {"steps": (1, 200000), "batch_size": (1, 256), "chunk_size": (1, 200)}
            clean = {}
            for key, (low, high) in allowed.items():
                value = settings.get(key, {"steps": 1000, "batch_size": 8, "chunk_size": 100}[key])
                if type(value) is not int or not low <= value <= high:
                    raise AppError(f"{key} must be an integer from {low} to {high}.")
                clean[key] = value
            clean["smoke"] = settings.get("smoke", False) is True
            base = body.get("base_model") or None
            if base:
                base = self.model_path(base)
                if clean["smoke"]:
                    raise AppError("A base model cannot be combined with the smoke architecture.")
            label = body.get("label", "")
            if not isinstance(label, str) or len(label) > 80 or any(ord(c) < 32 for c in label):
                raise AppError("Label must be at most 80 printable characters.")
            device = self._training_device(body, clean["smoke"])
            if self.store.rows("SELECT id FROM trainings WHERE state IN ('queued','running')"):
                raise AppError("A training run is already in progress.", 409)
            ident = str(uuid.uuid4())
            payload = {
                "export_id": exports[0]["id"],
                "settings": clean,
                "base_model": base,
                "label": label.strip(),
                "run_id": ident,
                "device": device,
            }
            self.store.execute(
                "INSERT INTO trainings (id,request_id,project_id,state,created,payload) VALUES (?,?,?,?,?,?)",
                (ident, request_id, project["id"], "queued", time.time(), json.dumps(payload)),
            )
            self.jobs.start(
                JobKind.TRAINING,
                ident,
                partial(self.jobs.train, self.agent_url, ident, payload, self.model_path),
            )
            return self.store.rows("SELECT * FROM trainings WHERE id=?", (ident,))[0]

    def training_progress(self, ident):
        rows = self.store.rows("SELECT * FROM trainings WHERE id=?", (ident,))
        if not rows:
            raise AppError("Training not found.", 404)
        if not self.agent_url or rows[0]["state"] not in ("queued", "running"):
            return {
                "run_id": ident,
                "status": rows[0]["state"],
                "percent": 100.0 if rows[0]["state"] == "complete" else 0.0,
            }
        try:
            report = remote_json(self.agent_url, f"/api/v1/trainings/{ident}/progress", timeout=10)
        except AppError as exc:
            if exc.status == 502:  # The run folder does not exist yet (image still starting).
                return {"run_id": ident, "status": "starting", "percent": 0.0, "step": 0, "eta_seconds": None}
            raise
        return {**report, "state": rows[0]["state"]}

    def abort_training(self, ident):
        with self.lock:
            rows = self.store.rows("SELECT * FROM trainings WHERE id=?", (ident,))
            if not rows:
                raise AppError("Training not found.", 404)
            if rows[0]["state"] not in ("queued", "running"):
                raise AppError("This training is not running.", 409)
            if not self.agent_url:
                raise AppError("Aborting needs the deployment agent.", 503)
        reply = remote_json(self.agent_url, "/api/v1/trainings/abort", {"run_id": ident}, timeout=90)
        if not isinstance(reply, dict) or reply.get("run_id") != ident or reply.get("state") != "aborting":
            raise AppError("Agent returned an invalid abort response.", 502)
        self.store.execute(
            "UPDATE trainings SET detail=? WHERE id=? AND state IN ('queued','running')",
            ("Abort requested; stopping the container.", ident),
        )
        return {"id": ident, "state": "aborting"}

    # ---- deployment -----------------------------------------------------------------------

    def policy(self, body):
        action = body.get("action")
        if action not in ("start", "stop"):
            raise AppError("Action must be start or stop.")
        request_id = self.request_id(body)
        with self.lock:
            previous = self.store.rows("SELECT * FROM deployments WHERE request_id=?", (request_id,))
            if previous:
                return previous[0]
            project = self.require_runtime_preset(body.get("project_id"))
            if not self.agent_url or self.runtime.mode != "ros":
                raise AppError("Policy deployment needs the ROS runtime and the deployment agent.", 409)
            running = self.store.rows("SELECT * FROM deployments WHERE state IN ('starting','running')")
            if action == "stop":
                if not running:
                    raise AppError("No policy is running.", 409)
                try:
                    self.runtime.select_source("none")
                except (RuntimeErrorDetail, TimeoutError):
                    pass  # The arbiter watchdog still stops forwarding when the policy source goes silent.
                remote_json(self.agent_url, "/api/v1/policy/down", {}, timeout=150)
                self.store.execute(
                    "UPDATE deployments SET state='stopped', ended=? WHERE state IN ('starting','running')",
                    (time.time(),),
                )
                self.store.execute(
                    "INSERT INTO deployments (id,request_id,project_id,state,created,payload,ended) VALUES (?,?,?,?,?,?,?)",
                    (
                        str(uuid.uuid4()),
                        request_id,
                        project["id"],
                        "stopped",
                        time.time(),
                        json.dumps({"action": "stop"}),
                        time.time(),
                    ),
                )
                return {"state": "stopped"}
            if running:
                raise AppError("A policy is already running. Stop it first.", 409)
            runtime = body.get("runtime") or "lerobot_act"
            if body.get("target") not in (None, "local") or runtime != "lerobot_act":
                self._check_runtime_choice(runtime, body.get("target"))
                raise AppError(
                    f"The policy source adapter for {RUNTIMES[runtime]['label']} is not built yet. "
                    "Use 'Get launch command' to run its server; the adapter is the next step.",
                    501,
                )
            if body.get("model_id"):
                chosen = self.project_model(body["model_id"], project["id"])
                if chosen.get("kind") == "hub":
                    raise AppError("Hub-only models can only run on a remote or GPU container.", 409)
                model = chosen["path"]
            else:
                model = self.model_path(body.get("model_path"))
            if self.runtime.status().get("active_source") not in ("none",):
                raise AppError("Set the control source to none before starting a policy.", 409)
            ident = str(uuid.uuid4())
            payload = {"model": model, "preset": project["preset"], "action": "start"}
            self.store.execute(
                "INSERT INTO deployments (id,request_id,project_id,state,created,payload) VALUES (?,?,?,?,?,?)",
                (ident, request_id, project["id"], "starting", time.time(), json.dumps(payload)),
            )
            try:
                remote_json(
                    self.agent_url,
                    "/api/v1/policy/up",
                    {"preset": project["preset"], "model": model},
                    timeout=150,
                )
            except AppError as exc:
                self.store.execute(
                    "UPDATE deployments SET state='failed',detail=?,ended=? WHERE id=?",
                    (str(exc), time.time(), ident),
                )
                raise
            self.store.execute(
                "UPDATE deployments SET state='running',detail=? WHERE id=?",
                ("Policy server and source are running. The arbiter is still on 'none'.", ident),
            )
            return self.store.rows("SELECT * FROM deployments WHERE id=?", (ident,))[0]

