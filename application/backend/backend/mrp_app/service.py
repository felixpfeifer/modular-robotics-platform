    def config_import(self, archive_path, apply=False, overwrite_calibrations=False):
        """Validate an uploaded bundle; with ``apply`` also store it. Nothing is stored if any check fails."""
        calibrations, note = self._local_calibrations()
        with self.lock:
            names = [row["name"] for row in self.store.rows("SELECT name FROM projects")]
        try:
            report = configbundle.read_bundle(archive_path, calibrations, self.robots(), names)
        except configbundle.BundleError as exc:
            raise AppError(str(exc)) from exc
        if note and report["items"]["calibrations"]:
            report["errors"].append(note)
            report["valid"], report["payload"] = False, None
        if note:
            report["warnings"].append(note)
        payload = report.pop("payload")
        report["applied"] = False
        if not apply:
            return report
        if payload is None:
            raise AppError("The bundle did not pass validation: " + "; ".join(report["errors"][:3]))
        stored, skipped = [], []
        for name, text in payload["calibrations"].items():
            current = calibrations.get(name)
            if current == text:
                continue
            if current is not None and not overwrite_calibrations:
                skipped.append(name)
                continue
            remote_json(self.agent_url, "/api/v1/devices/import-calibration", {"name": name, "content": text})
            stored.append(name)
        created = []
        with self.lock:
            for project in payload["projects"]:
                ident = str(uuid.uuid4())
                self.store.execute(
                    "INSERT INTO projects (id,name,created,cell_spec,preset,cell_layout) VALUES (?,?,?,?,?,?)",
                    (
                        ident,
                        project["name"],
                        time.time(),
                        json.dumps(project["cell_spec"]),
                        project["preset"],
                        json.dumps(project["cell_layout"]) if project["cell_layout"] else None,
                    ),
                )
                created.append({"id": ident, "name": project["name"]})
        report.update(
            applied=True,
            result={"calibrations_stored": stored, "calibrations_kept": skipped, "projects_created": created},
        )
        return report

