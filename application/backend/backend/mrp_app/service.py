    def cell(self, action, project_id=None, body=None):
        """Operate the cell. With a project id, the project's own preset, devices and flags are used."""
        if action not in ("up", "down", "status", "plan"):
            raise AppError("Unknown cell operation.")
        with self.lock:
            if action == "up":
                if not isinstance(project_id, str) or not project_id:
                    raise AppError("Select a project before starting the cell.", 400)
                self.project(project_id)
            if action == "down" and (
                self.runtime.status().get("active_episode_id")
                or self.store.rows(
                    "SELECT id FROM sessions WHERE state IN ('starting','recording','finalizing')"
                )
            ):
                raise AppError("Finish or cancel the recording before stopping the cell.", 409)
            if self.runtime.mode == "demo":
                return self.runtime.status() if action in ("status", "plan") else self.runtime.cell(action)
            if not self.agent_url:
                raise AppError("No deployment agent configured. Start the mock cell manually.", 503)
            if project_id:
                project = self.require_runtime_preset(project_id)
                preset, spec = project["preset"], project["cell_spec"]
            else:
                preset, spec = self.runtime_preset, {}
            selector = {"preset": preset, "task_id": spec.get("task_id", self.snapshot["task_id"])}
            if action in ("status", "plan"):
                return remote_json(self.agent_url, f"/api/v1/deployment/{action}?preset={preset}")
            if action == "up":
                selector["camera"] = spec.get("camera", "synthetic")
                for key in ("devices", "mock_motion", "settings", "images", "arms", "cameras"):
                    if key in spec:
                        selector[key] = spec[key]
                if (body or {}).get("operator_confirmed") is True:
                    selector["operator_confirmed"] = True
            return remote_json(
                self.agent_url,
                "/api/v1/deployment/" + action,
                selector,
                timeout=7300 if action == "up" else 150,
            )

    def devices(self, operation, body=None):
        """Discover and check USB devices through the deployment agent (the only host-level service)."""
        if not self.agent_url:
            raise AppError("No deployment agent configured, so devices cannot be scanned.", 503)
        if operation == "scan":
            return remote_json(self.agent_url, "/api/v1/devices/scan", timeout=30)
        if operation == "network":
            return remote_json(self.agent_url, "/api/v1/network", timeout=10)
        fields = DEVICE_OPERATIONS.get(operation)
        if fields is None or not isinstance(body, dict) or set(body) - fields:
            raise AppError("Unsupported device operation or fields.")
        return remote_json(self.agent_url, f"/api/v1/devices/{operation}", body, timeout=120)

