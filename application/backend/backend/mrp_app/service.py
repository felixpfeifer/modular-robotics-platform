    def snapshot_for(self, preset):
        """Recording configuration for a preset: the one generated for the last cell start."""
        if PRESETS[preset]["family"] != "mock" or self.runtime.mode != "ros":
            return self.snapshot
        from episode_recorder_py.configuration import load_workspace_config

        try:
            workspace = load_workspace_config(Path(CELL_WORKSPACE))
        except (OSError, ValueError, KeyError) as exc:
            if not PRESETS[preset]["hardware"]:
                return self.snapshot  # no cell has been started yet: the built-in mock defaults
            raise AppError(
                "The recording configuration for this cell has not been generated yet. Start the cell "
                f"once from the Record page ({exc}).",
                409,
            ) from exc
        result = copy.deepcopy(workspace)
        result["instruction"] = result["task"]["instruction"]
        result["minimum_duration_seconds"] = result["profile"].get("minimum_duration_seconds", 5)
        return result

