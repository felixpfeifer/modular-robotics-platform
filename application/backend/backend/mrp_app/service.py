    def register_hub_model(self, body):
        """Record a Hub model without downloading it; the serving container fetches it itself."""
        request_id = self.request_id(body)
        with self.lock:
            previous = self.store.rows("SELECT * FROM models WHERE id=?", (request_id,))
            if previous:
                return previous[0]
            project = self.project(body.get("project_id"))
            repo_id, runtime = body.get("repo_id"), body.get("runtime")
            if not isinstance(repo_id, str) or not hub.REPO.fullmatch(repo_id):
                raise AppError("Repository must use namespace/name syntax.")
            if runtime not in RUNTIMES:
                raise AppError("Choose the container this model is for.")
            revision = body.get("revision") or None
            if revision is not None and not re.fullmatch(r"[A-Za-z0-9_.\-/]{1,100}", revision):
                raise AppError("Invalid revision.")
            label = (body.get("label") or repo_id).strip()
            if len(label) > 80 or any(ord(c) < 32 for c in label):
                raise AppError("Label must be at most 80 printable characters.")
            self.store.execute(
                "INSERT INTO models (id,project_id,source,label,path,state,created,payload,detail,runtime,kind,repo_id,revision) "
                "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (
                    request_id,
                    project["id"],
                    "huggingface_ref",
                    label,
                    "",
                    "complete",
                    time.time(),
                    "{}",
                    "Stays on the Hugging Face Hub; the serving container downloads it with its own token.",
                    runtime,
                    "hub",
                    repo_id,
                    revision,
                ),
            )
            return self.store.rows("SELECT * FROM models WHERE id=?", (request_id,))[0]

    def launch_command(self, body):
        """A `docker run` for a remote host so it pulls the model/dataset from the Hub with a token."""
        purpose, runtime = body.get("purpose"), body.get("runtime")
        if purpose not in ("serve", "train") or runtime not in RUNTIMES:
            raise AppError("Choose purpose serve/train and a container.")
        image = body.get("image")
        if image:
            try:
                validate_images({"leader": image})
            except CellSpecError as exc:
                raise AppError(str(exc)) from exc
        target = None
        if body.get("target"):
            target = self.settings.target(body["target"])
            if target is None:
                raise AppError("Unknown remote target.", 404)
            if target["runtime"] != runtime:
                raise AppError("That target runs a different container.", 409)
        port = RUNTIMES[runtime]["default_port"]
        if target:
            port = int(target["url"].rsplit(":", 1)[1])
        repo = body.get("repo_id") or "<namespace>/<repo>"
        if body.get("repo_id") and not hub.REPO.fullmatch(repo):
            raise AppError("Repository must use namespace/name syntax.")
        revision = body.get("revision") or None
        steps = int(body.get("steps") or 1000)
        batch = int(body.get("batch_size") or 8)
        if not (1 <= steps <= 200000 and 1 <= batch <= 256):
            raise AppError("Steps or batch size out of range.")
        token_arg = "-e HF_TOKEN"
        if body.get("include_token") is True:
            if body.get("confirm_token") is not True:
                raise AppError("Confirm that you want the token written into the command.", 409)
            token = self.settings.target_token(target["id"]) if target else self.settings.token()
            if not token:
                raise AppError("No Hugging Face token available for this target.", 409)
            token_arg = f"-e HF_TOKEN={token}"
        cache = "-v hf_cache:/root/.cache/huggingface"
        rev = f" --revision {revision}" if revision else ""
        if runtime == "groot":
            image = image or "isaac-gr00t"  # build from the Isaac-GR00T repo's Dockerfile
            if purpose == "serve":
                inner = (
                    f"python scripts/inference_service.py --server --model-path {repo}{rev} "
                    f"--embodiment-tag new_embodiment --data-config so100 --port {port}"
                )
            else:
                inner = (
                    f"python scripts/gr00t_finetune.py --dataset-path <local dataset dir> --num-gpus 1 "
                    f"--max-steps {steps} --batch-size {batch} --output-dir /outputs --data-config so100"
                )
            command = f"docker run --rm --gpus all -p {port}:{port} {token_arg} {cache} {image} {inner}"
        elif purpose == "serve":
            inner = f"python -m lerobot.async_inference.policy_server --host=0.0.0.0 --port={port}"
            command = (
                f"docker run --rm -p {port}:{port} {token_arg} {cache} {image or 'lerobot-async'} {inner}"
            )
        else:
            inner = (
                f"lerobot-train --dataset.repo_id={repo} --policy.type=act --steps={steps} "
                f"--batch_size={batch} --policy.push_to_hub=true --policy.repo_id=<namespace>/<model-name>"
            )
            command = f"docker run --rm --gpus all {token_arg} {cache} {image or 'lerobot-train'} {inner}"
        notes = [
            "Use only trusted images compatible with the selected runtime."
            if body.get("image")
            else "Image names are placeholders: build or pull the official image and substitute it.",
            "Flags vary between Isaac-GR00T / LeRobot versions; check the project's README.",
        ]
        if purpose == "serve":
            notes.append("The server has no authentication. Reach it over an SSH tunnel or a VPN.")
        if token_arg == "-e HF_TOKEN":
            notes.append("export HF_TOKEN=… on the remote host first; the token is not part of this command.")
        return {"command": command, "notes": notes, "token_included": token_arg != "-e HF_TOKEN"}

    def _check_runtime_choice(self, runtime, target):
        """Validate a runtime/target pair; returns the target row (None for local)."""
        if runtime not in RUNTIMES:
            raise AppError("Unknown container.")
        if target in (None, "local"):
            item = RUNTIMES[runtime]
            if not item["local_serve"]:
                raise AppError(f"{item['label']} cannot run locally.", 409)
            if item["needs_gpu"] and not self.hardware().get("gpu"):
                raise AppError(f"{item['label']} needs an NVIDIA GPU on this machine; none detected.", 409)
            return None
        row = self.settings.target(target)
        if row is None:
            raise AppError("Unknown remote target.", 404)
        if row["runtime"] != runtime:
            raise AppError("That target runs a different container.", 409)
        return row

    def create_project(self, body):
        name = body.get("name", "")
        if not isinstance(name, str) or not 1 <= len(name.strip()) <= 80:
            raise AppError("Project name must contain 1–80 characters.")
        spec, preset = self._valid_spec(body.get("cell", DEFAULT_SPEC))
        ident = str(uuid.uuid4())
        self.store.execute(
            "INSERT INTO projects (id,name,created,cell_spec,preset) VALUES (?,?,?,?,?)",
            (ident, name.strip(), time.time(), json.dumps(spec), preset),
        )
        return self._with_cell(self.store.rows("SELECT * FROM projects WHERE id=?", (ident,))[0])

    def _valid_spec(self, spec):
        self.cameras()  # custom and discovered camera models are valid sources too
        try:
            return validate_spec(spec)
        except CellSpecError as exc:
            raise AppError(str(exc)) from exc

    @staticmethod
    def _with_cell(project):
        if not project.get("cell_spec"):  # created before per-project cells
            project["cell_spec"], project["preset"] = dict(DEFAULT_SPEC), "mock-so101"
        project["layout_saved"] = bool(project.get("cell_layout"))
        if not project["layout_saved"]:
            project["cell_layout"] = cell_layout.default_layout(project["preset"])
        else:
            # Normalise what older versions stored (e.g. free-text arm models such as "SO-101").
            try:
                project["cell_layout"] = cell_layout.validate_layout(project["cell_layout"])
            except cell_layout.LayoutError:
                pass  # serve it unchanged; saving it again reports the problem
        return project

    def project(self, ident):
        rows = self.store.rows("SELECT * FROM projects WHERE id=?", (ident,))
        if not rows:
            raise AppError("Project not found.", 404)
        return self._with_cell(rows[0])

    def set_cell(self, ident, body):
        spec, preset = self._valid_spec(body.get("cell"))
        with self.lock:
            self.project(ident)
            if self.store.rows(
                "SELECT id FROM sessions WHERE project_id=? AND state IN ('starting','recording','finalizing')",
                (ident,),
            ):
                raise AppError("Finish the active recording before changing the cell.", 409)
            if self.store.rows(
                "SELECT id FROM deployments WHERE project_id=? AND state IN ('starting','running')", (ident,)
            ):
                raise AppError("Stop the running policy before changing the cell.", 409)
            self.store.execute(
                "UPDATE projects SET cell_spec=?, preset=? WHERE id=?", (json.dumps(spec), preset, ident)
            )
            return self.project(ident)

    ACTIVE_SESSION = "state IN ('starting','recording','finalizing')"

    @staticmethod
    def _project_name(value):
        if not isinstance(value, str) or not 1 <= len(value.strip()) <= 80:
            raise AppError("Project name must contain 1–80 characters.")
        if any(ord(c) < 32 for c in value):
            raise AppError("Project name must not contain control characters.")
        return value.strip()

    def rename_project(self, ident, body):
        name = self._project_name(body.get("name"))
        with self.lock:
            self.project(ident)
            self.store.execute("UPDATE projects SET name=? WHERE id=?", (name, ident))
            return self.project(ident)

    def delete_project(self, ident, body):
        """Delete a project and everything the application derived for it.

        Raw recorder artifacts are never touched: episodes stay on disk and in the
        Episodes library, just without a project.
        """
        if body.get("confirm") is not True:
            raise AppError("Deleting a project needs explicit confirmation.")
        with self.lock:
            project = self.project(ident)
            busy = {
                "recording": f"SELECT id FROM sessions WHERE project_id=? AND {self.ACTIVE_SESSION}",
                "policy": "SELECT id FROM deployments WHERE project_id=? AND state IN ('starting','running')",
                "export": "SELECT id FROM jobs WHERE project_id=? AND state IN ('queued','running')",
                "training": "SELECT id FROM trainings WHERE project_id=? AND state IN ('queued','running')",
                "model import": "SELECT id FROM models WHERE project_id=? AND state='importing'",
            }
            for label, sql in busy.items():
                if self.store.rows(sql, (ident,)):
                    raise AppError(f"This project has a {label} in progress. Stop or finish it first.", 409)
            export_ids = [
                r["id"] for r in self.store.rows("SELECT id FROM jobs WHERE project_id=?", (ident,))
            ]
            models = self.store.rows("SELECT id,path FROM models WHERE project_id=?", (ident,))
            counts = {}
            with self.store.connection() as db:
                if export_ids:
                    marks = ",".join("?" * len(export_ids))
                    db.execute(
                        f"DELETE FROM uploads WHERE project_id=? OR json_extract(payload,'$.export_id') IN ({marks})",
                        (ident, *export_ids),
                    )
                else:
                    db.execute("DELETE FROM uploads WHERE project_id=?", (ident,))
                for table in ("sessions", "jobs", "trainings", "deployments", "models"):
                    counts[table] = db.execute(f"DELETE FROM {table} WHERE project_id=?", (ident,)).rowcount
                db.execute("DELETE FROM projects WHERE id=?", (ident,))
            freed = 0
            for folder in [self.exports_dir / i for i in export_ids] + [
                self.runs_dir / model["path"].split("/", 1)[0] for model in models
            ]:
                freed += self._remove_owned_folder(folder)
        return {"deleted": project["id"], "removed": counts, "freed_bytes": freed, "recordings_kept": True}

    @staticmethod
    def _remove_owned_folder(folder):
        """Remove an application-owned export/run folder; refuse anything that is not a real UUID folder."""
        if not canonical_uuid(folder.name) or folder.is_symlink() or not folder.is_dir():
            return 0
        size = sum(f.stat().st_size for f in folder.rglob("*") if f.is_file() and not f.is_symlink())
        shutil.rmtree(folder, ignore_errors=True)
        return size

