    def episodes(self):
        """Recorder artifacts joined with the application's own session/project metadata."""
        episodes, errors = self.artifacts.list()
        sessions = {
            row["id"]: row for row in self.store.rows("SELECT id,project_id,state,annotations FROM sessions")
        }
        names = {row["id"]: row["name"] for row in self.store.rows("SELECT id,name FROM projects")}
        for episode in episodes:
            session = sessions.get(episode["id"])
            project_id = (session or {}).get("project_id") or episode["manifest"].get("project_id")
            episode["project_id"] = project_id
            episode["project_name"] = names.get(project_id)
            episode["annotations"] = (session or {}).get("annotations", [])
            try:
                episode["size_bytes"] = sum(
                    f.stat().st_size for f in self.artifacts.mcap_files(episode["id"])
                )
            except (OSError, ValueError, FileNotFoundError):
                episode["size_bytes"] = None
        return {"episodes": episodes, "errors": errors}

    def episode_detail(self, ident):
        try:
            episode = self.artifacts.inspect(ident)
        except (ValueError, FileNotFoundError) as exc:
            raise AppError(str(exc), 404) from exc
        session = (self.store.rows("SELECT * FROM sessions WHERE id=?", (ident,)) or [None])[0]
        episode["project_id"] = (session or {}).get("project_id") or episode["manifest"].get("project_id")
        episode["session"] = session
        episode["project_name"] = None
        if episode["project_id"]:
            rows = self.store.rows("SELECT name FROM projects WHERE id=?", (episode["project_id"],))
            episode["project_name"] = rows[0]["name"] if rows else None
        return episode

