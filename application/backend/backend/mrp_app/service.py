    def export(self, body):
        request_id = self.request_id(body)
        with self.lock:
            previous = self.store.rows("SELECT * FROM jobs WHERE request_id=?", (request_id,))
            if previous:
                return previous[0]
            if self.runtime.mode != "ros" or not self.agent_url:
                raise AppError(
                    "Dataset export requires ROS recordings and the deployment agent. UI demo data cannot be exported.",
                    409,
                )
            project = self.require_runtime_preset(body.get("project_id"))
            ids = body.get("episode_ids")
            if not isinstance(ids, list) or len(ids) > 1000 or not all(isinstance(x, str) for x in ids):
                raise AppError("episode_ids must be a list of at most 1000 UUIDs.")
            repo_id = body.get("repo_id", "local/mock-so101")
            if not isinstance(repo_id, str) or not re.fullmatch(r"[A-Za-z0-9_-]+/[A-Za-z0-9_.-]+", repo_id):
                raise AppError(
                    "repo_id must use organization/dataset syntax; it is a local identifier, not an upload."
                )
            ratio = body.get("downsample_hz_ratio", 1)
            if type(ratio) is not int or not 1 <= ratio <= 120:
                raise AppError("downsample_hz_ratio must be an integer between 1 and 120.")
            try:
                selection = self.artifacts.selection(ids)
            except (ValueError, OSError) as exc:
                raise AppError(str(exc), 409) from exc
            if self.store.rows("SELECT id FROM jobs WHERE state IN ('queued','running')"):
                raise AppError("An export job is already running.", 409)
            ident = str(uuid.uuid4())
            folder = self.exports_dir / ident
            folder.mkdir()
            (folder / "accepted.json").write_text(json.dumps(selection, indent=2) + "\n")
            payload = {
                "job_id": ident,
                "repo_id": repo_id,
                "downsample_hz_ratio": ratio,
                "episode_ids": ids,
                "format": "LeRobot v3",
                "selection": str(folder / "accepted.json"),
                "output": str(folder / "dataset"),
                "snapshot": self.snapshot_for(project["preset"]),
                "preset": project["preset"],
            }
            self.store.execute(
                "INSERT INTO jobs (id,request_id,state,created,payload,detail,project_id) VALUES (?,?,?,?,?,?,?)",
                (ident, request_id, "queued", time.time(), json.dumps(payload), "", project["id"]),
            )
            self.jobs.start(
                JobKind.EXPORT,
                ident,
                partial(self.jobs.export, self.agent_url, ident, repo_id, self.runtime_preset, ratio),
            )
            return self.store.rows("SELECT * FROM jobs WHERE id=?", (ident,))[0]

    def upload(self, body):
        if set(body) - {
            "request_id",
            "export_id",
            "repo_id",
            "visibility",
            "token",
            "confirm_upload",
            "confirm_public",
            "use_saved_token",
        }:
            raise AppError("Unknown upload fields.")
        request_id = self.request_id(body)
        export_id, repo_id = body.get("export_id"), body.get("repo_id")
        visibility = body.get("visibility", "private")
        if not canonical_uuid(export_id):
            raise AppError("Select a completed export.")
        if not isinstance(repo_id, str) or not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", repo_id
        ):
            raise AppError("Repository must use namespace/name syntax.")
        if visibility not in ("private", "public") or body.get("confirm_upload") is not True:
            raise AppError("Explicit upload confirmation and valid visibility are required.")
        if visibility == "public" and body.get("confirm_public") is not True:
            raise AppError("Public upload requires a separate confirmation.")
        payload = {"export_id": export_id, "repo_id": repo_id, "visibility": visibility}
        with self.lock:
            previous = self.store.rows("SELECT * FROM uploads WHERE request_id=?", (request_id,))
            if previous:
                if previous[0]["payload"] != payload:
                    raise AppError("Request ID already belongs to a different upload.", 409)
                return previous[0]
            if self.runtime.mode != "ros" or not self.agent_url:
                raise AppError("Upload requires the ROS export workflow and deployment agent.", 409)
            token = self.settings.token() if body.get("use_saved_token") else body.get("token")
            if (
                not isinstance(token, str)
                or not 1 <= len(token) <= 4096
                or any(c in token for c in "\r\n\x00")
            ):
                raise AppError("Provide a Hugging Face token.")
            exports = self.store.rows("SELECT * FROM jobs WHERE id=? AND state='complete'", (export_id,))
            if not exports:
                raise AppError("Only a completed local export can be uploaded.", 409)
            folder = self.exports_dir / export_id
            if (
                folder.is_symlink()
                or (folder / "dataset").is_symlink()
                or not (folder / "dataset/meta/info.json").is_file()
            ):
                raise AppError("Export dataset is missing or is a symlink.", 409)
            if self.store.rows("SELECT id FROM uploads WHERE state IN ('queued','running')"):
                raise AppError("An upload is already running.", 409)
            ident = str(uuid.uuid4())
            self.store.execute(
                "INSERT INTO uploads (id,request_id,state,created,payload) VALUES (?,?,?,?,?)",
                (ident, request_id, "queued", time.time(), json.dumps(payload)),
            )
            self.jobs.start(
                JobKind.UPLOAD, ident, partial(self.jobs.upload, self.agent_url, ident, payload, token)
            )
            return self.store.rows("SELECT * FROM uploads WHERE id=?", (ident,))[0]

