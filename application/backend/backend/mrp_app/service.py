    def hardware(self):
        """GPU report from the deployment agent, cached briefly. No agent means no local GPU."""
        cached = getattr(self, "_hardware", None)
        if cached and time.monotonic() - cached[0] < 60:
            return cached[1]
        report = {"gpu": False, "name": "", "vram_gb": 0, "detail": "No deployment agent configured."}
        if self.agent_url:
            try:
                report = remote_json(self.agent_url, "/api/v1/hardware", timeout=30)
            except AppError as exc:
                report["detail"] = str(exc)
        self._hardware = (time.monotonic(), report)
        return report

    def robots(self):
        """Robot profiles (joint names, topics) from the deployment agent, cached briefly."""
        cached = getattr(self, "_robots", None)
        if cached and time.monotonic() - cached[0] < 60:
            return cached[1]
        profiles = {}
        if self.agent_url:
            try:
                profiles = remote_json(self.agent_url, "/api/v1/robots", timeout=10)
            except AppError:
                profiles = {}
        self._robots = (time.monotonic(), profiles)
        return profiles

    # ---- Camera models: built-in, discovered on the host, custom --------------------------

    def cameras(self, refresh=False):
        """The camera catalogue, and the models cell validation accepts. Cached for 15 seconds.

        With an agent this is the agent's view (it sees the driver images); without one, the
        built-in models plus the custom ones stored here, with no "installed" information.
        """
        cached = getattr(self, "_cameras", None)
        if cached and not refresh and time.monotonic() - cached[0] < 15:
            return cached[1]
        report, problems = None, []
        if self.agent_url:
            try:
                report = remote_json(
                    self.agent_url, "/api/v1/cameras" + ("?refresh=1" if refresh else ""), timeout=90
                )
            except AppError as exc:
                problems.append(str(exc))
            if not isinstance(report, dict) or not isinstance(report.get("models"), dict):
                report = None
        custom, stored_problems = camera_models.load_custom(self.camera_models_file)
        if report is None:
            camera_models.set_extra(custom)
            report = camera_models.describe(problems=problems + stored_problems)
            report["custom_store"] = True
        else:
            # Re-check what the agent reports before cells may use it.
            extra = {}
            for ident, model in list(report["models"].items()):
                if model.get("origin") in ("custom", "discovered"):
                    try:
                        manifest = {
                            k: v for k, v in camera_models.to_manifest(ident, model).items() if k != "image"
                        }
                        extra[ident] = camera_models.parse_manifest(
                            manifest, model["image"], model["origin"]
                        )[1]
                    except (camera_models.CameraModelError, KeyError, TypeError):
                        report["models"].pop(ident, None)
            camera_models.set_extra(extra)
            if custom and not report.get("custom_store"):
                report.setdefault("problems", []).append(
                    "The deployment agent does not see the custom cameras: give it the camera-models "
                    "volume and MRP_CAMERA_MODELS_FILE (see the README)."
                )
        self._cameras = (time.monotonic(), report)
        return report

    def _custom_entries(self):
        try:
            stored = json.loads(self.camera_models_file.read_text())
        except FileNotFoundError:
            return []
        except (OSError, ValueError) as exc:
            raise AppError(f"Custom cameras could not be read: {exc}", 500) from exc
        return [
            e
            for e in (stored.get("models") if isinstance(stored, dict) else None) or []
            if isinstance(e, dict)
        ]

    def _write_custom(self, entries):
        self.camera_models_file.parent.mkdir(parents=True, exist_ok=True)
        temporary = self.camera_models_file.with_suffix(".tmp")
        temporary.write_text(json.dumps({"schema_version": 1, "models": entries}, indent=2) + "\n")
        temporary.replace(self.camera_models_file)
        self._cameras = None

    def add_camera_model(self, body):
        """Add or replace a custom camera model. Its image runs with the model's device access."""
        if not isinstance(body, dict):
            raise AppError("Send the camera model as an object.")
        if body.get("trusted") is not True:
            raise AppError(
                "Confirm that you trust this image: it runs on the deployment host and, for USB "
                "cameras, gets the host's USB bus."
            )
        manifest = {k: v for k, v in body.items() if k not in ("image", "trusted", "pull")}
        try:
            ident, model = camera_models.parse_manifest(manifest, body.get("image"), "custom")
        except camera_models.CameraModelError as exc:
            raise AppError(str(exc)) from exc
        with self.lock:
            entries = [e for e in self._custom_entries() if e.get("id") != ident]
            if len(entries) >= camera_models.MAX_EXTRA_MODELS:
                raise AppError(f"At most {camera_models.MAX_EXTRA_MODELS} custom cameras.")
            entries.append(camera_models.to_manifest(ident, model))
            self._write_custom(entries)
        pulled = self.pull_camera_model(ident) if body.get("pull") is True and self.agent_url else None
        return {"id": ident, "pull": pulled, "cameras": self.cameras(refresh=True)}

    def delete_camera_model(self, ident):
        with self.lock:
            entries = self._custom_entries()
            if not any(e.get("id") == ident for e in entries):
                raise AppError("Custom camera not found.", 404)
            users = [
                p["name"] for p in self.store.rows("SELECT * FROM projects") if self._uses_camera(p, ident)
            ]
            if users:
                raise AppError(
                    f"Camera '{ident}' is used by: {', '.join(users)}. Change those cells first.", 409
                )
            self._write_custom([e for e in entries if e.get("id") != ident])
        return {"id": ident, "cameras": self.cameras(refresh=True)}

    @staticmethod
    def _uses_camera(project, ident):
        def decoded(value):  # the store decodes JSON columns; tolerate raw text too
            if isinstance(value, str):
                try:
                    value = json.loads(value)
                except ValueError:
                    return {}
            return value if isinstance(value, dict) else {}

        spec, layout = decoded(project.get("cell_spec")), decoded(project.get("cell_layout"))
        cameras = spec.get("cameras") or []
        modules = (layout or {}).get("modules") or []
        return any(ident in (c.get("source"), c.get("model")) for c in cameras if isinstance(c, dict)) or any(
            isinstance(m, dict) and (m.get("properties") or {}).get("model") == ident for m in modules
        )

    def pull_camera_model(self, ident):
        """Pull a custom or discovered model's driver image through the agent."""
        if not self.agent_url:
            raise AppError("No deployment agent configured, so images cannot be pulled.", 503)
        try:
            result = remote_json(self.agent_url, "/api/v1/cameras/pull", {"model": ident}, timeout=960)
        finally:
            self._cameras = None
        return {k: v for k, v in result.items() if k != "catalog"}

    def catalog(self):
        cameras = self.cameras()
        hardware = self.hardware()
        runtimes = {}
        for key, item in RUNTIMES.items():
            blocked = item["needs_gpu"] and not hardware.get("gpu")
            runtimes[key] = {
                **item,
                "local_available": item["local_serve"] and not blocked,
                "local_reason": "Needs an NVIDIA GPU on this machine; none detected." if blocked else "",
            }
        layout = cell_layout.describe()
        for ident, choice in layout["module_types"]["camera"].get("models", {}).items():
            if "installed" in cameras["models"].get(ident, {}):
                choice["installed"] = cameras["models"][ident]["installed"]
        return {
            **describe(),
            "cameras": cameras,
            "runtimes": runtimes,
            "hardware": hardware,
            "robots": self.robots(),
            "layout": layout,
        }

