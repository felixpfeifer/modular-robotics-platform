"""Generate a Jupyter notebook that trains an ACT policy on a remote GPU server."""

import json


def _cell(kind, source):
    cell = {"cell_type": kind, "metadata": {}, "source": source.strip("\n").splitlines(True)}
    if kind == "code":
        cell.update({"execution_count": None, "outputs": []})
    return cell


def build(project_name, task, settings, source, repo_id=None):
    """`source` is 'hub' (dataset on the Hugging Face Hub) or 'zip' (uploaded dataset.zip)."""
    steps, batch, chunk = settings["steps"], settings["batch_size"], settings["chunk_size"]
    if source == "hub":
        fetch = f"""
from huggingface_hub import snapshot_download
DATASET_REPO = {repo_id!r}
DATASET_DIR = snapshot_download(DATASET_REPO, repo_type="dataset", token=os.environ.get("HF_TOKEN") or None)
print("dataset at", DATASET_DIR)"""
    else:
        fetch = """
import zipfile
# Upload dataset.zip (downloaded from the MRP Dataset page) next to this notebook.
DATASET_DIR = Path("dataset"); DATASET_DIR.mkdir(exist_ok=True)
with zipfile.ZipFile("dataset.zip") as archive:
    archive.extractall(DATASET_DIR)
print("dataset at", DATASET_DIR.resolve())"""
    cells = [
        _cell(
            "markdown",
            f"""# Train an ACT policy: {project_name}
Task: *{task}*

Generated by MRP. Runs LeRobot **0.6.1** on a GPU machine. When it finishes, download
`pretrained_model.zip` and import it on the project's **Train** page ("Import checkpoint file").
Use the same LeRobot version MRP used to write the dataset.""",
        ),
        _cell(
            "code",
            """
%pip install -q "lerobot==0.6.1" huggingface_hub
import os, subprocess, sys
from pathlib import Path
import torch
print("CUDA available:", torch.cuda.is_available())""",
        ),
        _cell(
            "code",
            "# Optional (only for a private dataset repo). Do not commit this notebook with a token in it.\n# os.environ['HF_TOKEN'] = '...'",
        ),
        _cell("code", fetch),
        _cell(
            "code",
            f"""
STEPS, BATCH_SIZE, CHUNK_SIZE = {steps}, {batch}, {chunk}
OUTPUT = Path("outputs/act"); 
cmd = [
    "lerobot-train", "--dataset.repo_id=local/mrp-task", f"--dataset.root={{DATASET_DIR}}",
    "--policy.type=act", f"--policy.device={{'cuda' if torch.cuda.is_available() else 'cpu'}}",
    "--policy.push_to_hub=false", f"--policy.chunk_size={{CHUNK_SIZE}}", f"--policy.n_action_steps={{CHUNK_SIZE}}",
    f"--output_dir={{OUTPUT}}", f"--steps={{STEPS}}", f"--batch_size={{BATCH_SIZE}}",
    "--wandb.enable=false", "--save_checkpoint=true", f"--save_freq={{STEPS}}",
]
subprocess.run(cmd, check=True)""",
        ),
        _cell(
            "code",
            """
import shutil
model = OUTPUT / "checkpoints" / "last" / "pretrained_model"
required = ["config.json", "model.safetensors", "policy_preprocessor.json", "policy_postprocessor.json"]
missing = [name for name in required if not (model / name).is_file()]
assert not missing, f"checkpoint incomplete: {missing}"
shutil.make_archive("pretrained_model", "zip", model)
print("Download pretrained_model.zip and import it in MRP (Train -> Import checkpoint file).")""",
        ),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def dumps(*args, **kwargs):
    return json.dumps(build(*args, **kwargs), indent=1)
